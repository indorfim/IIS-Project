SYSTEM_PROMPTS: dict[str, str] = {
    "analyst": ANALYST_PROMPT,
    "clarifier": CLARIFIER_PROMPT
}


def format_chunks(chunks: list[Chunk]) -> str:
    """Развернуть найденные фрагменты в текстовый блок. Готово, менять не нужно."""
    if not chunks:
        return "(база знаний ничего не вернула)"
    # Страница печатается, только когда она есть: у markdown и текстовых файлов
    # page = 0, и «стр. 0» в каждом фрагменте учит модель дописывать в ссылку
    # номер, которого в контексте нет.
    return "\n\n".join(
        f"[{c.source}, стр. {c.page}] (близость {c.score})\n{c.text}" if c.page
        else f"[{c.source}] (близость {c.score})\n{c.text}"
        for c in chunks
    )


def build_messages(role: str, question: str, chunks: list[Chunk],
                   history: list[Message]) -> list[dict]:
    """Собрать список сообщений для LLM."""
    messages = []
    
    #  Системный промпт
    messages.append({"role": "system", "content": SYSTEM_PROMPTS[role]})
    
    #  История диалога (при наличии)
    for msg in history:
        messages.append({"role": msg.role, "content": msg.content})
        
    # Текущий вопрос пользователя и найденные контекстные фрагменты
    chunks_text = format_chunks(chunks)
